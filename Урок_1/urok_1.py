# 3. Типы данных
# ------------------------------------------------------------
print("\n=== 3. Типы данных ===")

a = 10
b = 3.14
c = "Привет"

print(type(a))  # <class 'int'>
print(type(b))  # <class 'float'>
print(type(c))  # <class 'str'>

# Динамическая типизация — тип меняется при присваивании
x = 10
print(type(x))  # int

x = 3.14
print(type(x))  # float

x = "текст"
print(type(x))  # str

# ------------------------------------------------------------
# 4. Переменные (ссылки на объекты)
# ------------------------------------------------------------
print("\n=== 4. Переменные ===")

a = 7
print(a)  # 7

b = a  # b ссылается на тот же объект, что и a
a = 10  # a теперь ссылается на новый объект
print(a, b)  # 10 7

# Множественное присваивание
a, b = 1, 2
print(a, b)  # 1 2

# Обмен значениями
a, b = b, a
print(a, b)  # 2 1

# Цепное присваивание
a = b = c = 0
print(a, b, c)  # 0 0 0

