# ------------------------------------------------------------
# 6. Арифметические операции
# ------------------------------------------------------------
print("\n=== 6. Арифметические операции ===")

print(2 + 3)  # 5
print(10 - 4)  # 6
print(3 * 5)  # 15
print(7 / 2)  # 3.5   (всегда float)
print(7 // 2)  # 3     (целочисленное деление)
print(7 % 2)  # 1     (остаток)
print(2 ** 3)  # 8     (степень)

# Приоритет операций
print(2 + 3 * 5)  # 17
print((2 + 3) * 5)  # 25
print(2 ** 3 ** 2)  # 512  (справа налево)

# Сокращённые операторы
i = 5
i += 1
print(i)  # 6

i *= 3
print(i)  # 18

i //= 2
print(i)  # 9

