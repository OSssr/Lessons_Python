# 6. Основы принятия решений (if / elif / else)
# ------------------------------------------------------------
print("\n=== 6. Основы принятия решений ===")
# Программа может выбирать, какой код выполнять, в зависимости от условия.
# Булевы значения: True и False.
# Операторы сравнения: ==, !=, <, >, <=, >=
# Булевы операторы: and, or, not

# Синтаксис условия:
# if условие:
#     # блок кода выполняется, если условие True
# elif другое_условие:
#     # блок кода выполняется, если предыдущие условия False, а это True
# else:
#     # блок кода выполняется, если все условия выше False

name = "Гость"
age = 20

if name == "Админ":
    print("Здравствуйте, администратор!")
elif age < 18:
    print("Доступ запрещён")
else:
    print(f"Добро пожаловать, {name}!")

# Важные правила:
# - После if, elif и else обязательно ставится двоеточие.
# - Блок кода записывается с отступом (обычно 4 пробела).
# - Выполняется только один блок из всей цепочки.
# - Порядок elif имеет значение — проверка идёт сверху вниз.


