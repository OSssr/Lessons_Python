# ------------------------------------------------------------
# 1. Что такое строка
# ------------------------------------------------------------
# Строка в Python — это упорядоченный набор символов. 
# Каждый символ занимает своё место и имеет порядковый номер (индекс).

print("=== 1. Что такое строка ===")
# Строки можно создавать несколькими способами:
s1 = "Панда"          # в двойных кавычках
s2 = 'Panda'          # в одинарных кавычках
s3 = '''Я Python бы выучил только за то,
что есть популярные курсы.
Много хороших курсов!''' # в тройных кавычках (для многострочного текста)

print(s1)
print(s2)
print(s3)

# Если забыть поставить кавычки, Python воспримет слово как имя переменной и выдаст ошибку.
# Пустая строка записывается так: "" или ''. Даже один пробел уже делает строку непустой.
empty = ""
space = " "
print("Длина пустой строки:", len(empty))
print("Длина строки с пробелом:", len(space))


# ------------------------------------------------------------
# 2. Базовые операции со строками
# ------------------------------------------------------------
print("\n=== 2. Базовые операции со строками ===")

# Конкатенация (сложение строк)
s1 = "Я люблю"
s2 = "язык Python"
s3 = s1 + " " + s2
print("Конкатенация:", s3)

# Нельзя напрямую складывать строку и число. Сначала число нужно превратить в строку.
age = 25
# print("Мне " + age + " лет")  # Ошибка!
print("Мне " + str(age) + " лет")  # Правильно

# Длина строки
print("Длина 'hello':", len("hello"))     # 5
print("Длина '':", len(""))               # 0

# Проверка вхождения подстроки
print("'ab' in 'abracadabra':", 'ab' in "abracadabra")    # True
print("'abc' in 'abracadabra':", 'abc' in "abracadabra")  # False

# Сравнение строк (лексикографическое)
# Заглавные буквы в таблице символов идут раньше строчных.
print("'кот' > 'кит':", 'кот' > 'кит')     # True
print("'Кот' > 'кот':", 'Кот' > 'кот')     # False


# ------------------------------------------------------------
# 3. Индексы и срезы
# ------------------------------------------------------------
print("\n=== 3. Индексы и срезы ===")
# Каждый символ строки имеет индекс. Нумерация начинается с нуля.
s = "hello python"
print("s[0]:", s[0])      # 'h'
print("s[1]:", s[1])      # 'e'
print("s[-1]:", s[-1])    # 'n' (последний символ)
print("s[-2]:", s[-2])    # 'o'

# Попытка обратиться к несуществующему индексу вызывает ошибку.
# print(s[100])  # IndexError

# Срезы позволяют выделить сразу несколько символов:
# s[start:stop]        # от start до stop (не включая stop)
# s[start:stop:step]   # с шагом step
print("s[1:5]:", s[1:5])       # 'ello'
print("s[:5]:", s[:5])         # 'hello'
print("s[6:]:", s[6:])         # 'python'
print("s[::2]:", s[::2])       # каждый второй символ
print("s[::-1]:", s[::-1])     # строка в обратном порядке

# Важно: строки в Python неизменяемы.
# s[0] = 'H'  # TypeError
# Чтобы изменить строку, нужно создать новую:
s2 = 'H' + s[1:]
print("Новая строка:", s2)


# ------------------------------------------------------------
# 4. Основные методы строк
# ------------------------------------------------------------
print("\n=== 4. Основные методы строк ===")
# Метод — это функция, связанная с объектом. Вызывается через точку.

print("'python'.upper():", "python".upper())             # Переводит в верхний регистр
print("'PYTHON'.lower():", "PYTHON".lower())             # Переводит в нижний регистр
print("'abracadabra'.count('ra'):", "abracadabra".count("ra")) # Считает вхождения
print("'hello'.find('l'):", "hello".find("l"))           # Индекс первого вхождения
print("'hello'.replace('l', 'L'):", "hello".replace("l", "L")) # Замена
print("'hello'.isalpha():", "hello".isalpha())           # Только буквы?
print("'123'.isdigit():", "123".isdigit())               # Только цифры?
print("'a b c'.split():", "a b c".split())               # Разбивает на список
print("' '.join(['a', 'b']):", " ".join(["a", "b"]))     # Объединяет список в строку
print("' hello '.strip():", "'" + " hello ".strip() + "'") # Удаляет пробелы по краям

# Все методы возвращают новую строку. Исходная строка при этом не меняется.


